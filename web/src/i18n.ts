export type StringKey = keyof typeof en;

// English only at first. The other dictionary is a separate chunk, fetched
// during boot when it is the language in play and never otherwise.
const dictionaries: Partial<Record<Language, Record<StringKey, string>>> = { en };

/**
 * Brings in the dictionary for a language, if it is not the built-in one and
 * has not already arrived. Awaited once during boot so the first paint is
 * already translated; everything after that reads it synchronously.
 */
export async function loadLanguage(next: Language = active): Promise<void> {
  if (dictionaries[next]) return;
  if (next === 'zh') {
    dictionaries.zh = (await import('./i18n.zh')).zh;
  }
}

let active: Language = detect();

function detect(): Language {
  try {
    const stored = localStorage.getItem(LANGUAGE_KEY);
    if (stored === 'en' || stored === 'zh') return stored;
  } catch {
    // Storage disabled; fall through to the browser's preference.
  }
  return (navigator.language || 'en').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function language(): Language {
  return active;
}

/**
 * Returns the load of the new dictionary, so a caller that needs the next
 * render translated can wait for it. Ignoring it is safe: until the chunk
 * lands, t() falls back to English rather than to nothing.
 */
export function setLanguage(next: Language): Promise<void> {
  active = next;
  try {
    localStorage.setItem(LANGUAGE_KEY, next);
  } catch {
    // Best effort; the choice still applies for this page load.
  }
  return loadLanguage(next);
}

/** Looks up a string, substituting {name} placeholders. */
export function t(key: StringKey, vars?: Record<string, string | number>): string {
  const value = dictionaries[active]?.[key] ?? en[key] ?? key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/**
 * Picks between two keys by count. English needs the distinction; Chinese
 * does not, and its two entries are simply the same sentence — which is
 * cheaper than a plural-rules engine for the four places this arises.
 */
export function tn(
  count: number,
  one: StringKey,
  other: StringKey,
  vars?: Record<string, string | number>,
): string {
  return t(count === 1 ? one : other, { count, ...vars });
}
