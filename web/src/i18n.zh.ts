// The Chinese dictionary, in a module of its own so it is fetched only by
// someone reading Chinese. English stays in the main bundle because it is
// also the fallback: t() renders the English sentence for any key this file
// has not supplied, which is what makes loading it late harmless rather than
// a screen full of key names. The backoffice's English is the one part that
// is not in the main bundle (i18n.admin.ts), and the screens that read it are
// in the same chunk, so where it is needed it is there.
//
// The backoffice's Chinese is split the same way, into i18n.admin.zh.ts: it
// was most of this chunk, and every Chinese reader fetched it to open a
// conversation. It is a chunk of its own rather than part of the
// backoffice's, so an English-reading administrator does not download it
// either; loadLanguage in i18n.ts fetches it once the backoffice is in play.
//
// The type is what keeps it complete. `Record<CoreKey, string>` over the keys
// derived from the English source means a key added there and forgotten here
// is a tsc error, not a sentence that quietly falls back. Splitting the file
// does not loosen that, and `import type` leaves no runtime cycle.

