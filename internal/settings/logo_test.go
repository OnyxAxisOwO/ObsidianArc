package settings

import "testing"

func TestDetectLogoMedia(t *testing.T) {
	cases := []struct {
		name string
		data []byte
		want string
		err  bool
	}{
		{
			name: "png",
			data: []byte("\x89PNG\r\n\x1a\n\x00\x00\x00\rIHDR"),
			want: "image/png",
		},
		{
			name: "jpeg",
			data: []byte("\xFF\xD8\xFF\xE0\x00\x10JFIF\x00\x01"),
			want: "image/jpeg",
		},
		{
			name: "gif",
			data: []byte("GIF89a\x01\x00\x01\x00"),
			want: "image/gif",
		},
		{
			name: "webp",
			data: []byte("RIFF\x00\x00\x00\x00WEBPVP8 "),
			want: "image/webp",
		},
		{
			name: "ico",
			data: []byte("\x00\x00\x01\x00\x01\x00\x10\x10"),
			want: "image/x-icon",
		},
		{
			name: "svg standard",
			data: []byte("<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'><circle cx='50' cy='50' r='40'/></svg>"),
			want: "image/svg+xml",
		},
		{
			name: "svg with xml declaration",
			data: []byte("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<svg viewBox=\"0 0 24 24\"></svg>"),
			want: "image/svg+xml",
		},
		{
			name: "svg with utf8 bom",
			data: append([]byte("\xef\xbb\xbf"), []byte("<svg viewBox=\"0 0 24 24\"></svg>")...),
			want: "image/svg+xml",
		},
		{
			name: "svg with comment and doctype",
			data: []byte("<!-- Generated by app -->\n<!DOCTYPE svg PUBLIC \"-//W3C//DTD SVG 1.1//EN\" \"http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd\">\n<svg width=\"100\"></svg>"),
			want: "image/svg+xml",
		},
		{
			name: "invalid text",
			data: []byte("hello world not an image"),
			err:  true,
		},
		{
			name: "too short",
			data: []byte("a"),
			err:  true,
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := DetectLogoMedia(tc.data)
			if tc.err {
				if err == nil {
					t.Fatalf("expected error, got %s", got)
				}
				return
			}
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if got != tc.want {
				t.Fatalf("DetectLogoMedia() = %q, want %q", got, tc.want)
			}
		})
	}
}
