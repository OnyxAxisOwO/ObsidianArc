// A numbered placeholder is the explicit policy of strict mode. Keeping the
// spelling narrow leaves names with a chosen suffix to the model and cohort.
func strictNumberedPlaceholder(username string) bool {
	name := strings.ToLower(strings.TrimSpace(username))
	for _, prefix := range []string{"user", "guest", "member", "test"} {
		if !strings.HasPrefix(name, prefix) {
			continue
		}
		suffix := strings.TrimPrefix(name, prefix)
		suffix = strings.TrimPrefix(suffix, "_")
		if len(suffix) < 4 {
			return false
		}
		for _, ch := range suffix {
			if ch < '0' || ch > '9' {
				return false
			}
		}
		return true
	}
	return false
}

// DefaultPrompt is the shared part of the system instruction shown in the
// security settings form. The mode rules remain server-owned and are always
// appended, so the prompt visible to an operator cannot silently remove them.
func DefaultPrompt() string { return commonInstruction }

func instructionForPrompt(mode Mode, prompt string) string {
	return instructionFor(mode, prompt)
}

const responseFormatInstruction = `Choose one decision:
- allow: the details look like an ordinary person.
- restrict: the account may be a real person, but there are ambiguous or mildly suspicious signs.
  It may register and use the website while programmatic API access is held back. (Do NOT use
  restrict for automated registration bots or templated machine usernames; those must be refused).
- refuse: the details are unmistakably automated, disposable, or hostile (including all bot
  registration machine templates like userXXXXX or word+digits+site like hawk0344onyx).

The "reason" field will be recorded directly into the administrator security log, so write it in Simplified Chinese (简体中文). Keep it to one short sentence explaining your judgement.

Answer with JSON and nothing else:
{"decision": "allow|restrict|refuse", "reason": "<one short sentence in Simplified Chinese>"}`

// instructionFor is the whole prompt for one mode, optionally incorporating an
// administrator's custom prompt.
func instructionFor(mode Mode, custom ...string) string {
	customPrompt := ""
	if len(custom) > 0 {
		customPrompt = strings.TrimSpace(custom[0])
	}
	base := commonInstruction
	if customPrompt != "" {
		base = customPrompt
		// If the custom prompt does not include the decision schema,
		// append it so that the model's response remains structured and parseable.
		if !strings.Contains(customPrompt, `{"decision"`) {
			base = base + "\n\n" + responseFormatInstruction
		}
	}
	bias, ok := modeInstruction[mode]
	if !ok {
		bias = modeInstruction[Normal]
	}
	return base + "\n\n" + bias
}

// Reviewer asks one model.
type Reviewer struct {
	Registry *adapter.Registry
	// Resolves the configured model to something callable. Injected so this
	// package depends on neither the model store nor the provider store —
	// both of which would drag most of the server in behind them.
	Resolve func(ctx context.Context) (adapter.Provider, adapter.ModelSpec, error)
	// Prompt supplies an optional operator-configured prompt. If nil or returning
	// empty, the built-in instruction is used.
	Prompt func() string
	// CustomPrompt is an alias for Prompt for compatibility.
	CustomPrompt func() string
}

// Review returns how the registration should proceed.
//
// What happens when it cannot answer depends on the mode, and it is the one
// place the three differ in more than wording.
//
// Loose allows a failed review. Normal restricts API access while still
// admitting the account. This contains the higher-cost capability without
// turning an upstream outage into an outage of the registration page.
//
// Strict fails closed, because an operator who has chosen it has said that a
// junk account costs more than a turned-away visitor. The consequence is
// blunt and worth stating: while the model is unreachable, nobody registers.
//
// The error is returned alongside the verdict rather than instead of it, so a
// caller both acts on the decision and can say in the log why it was made
// without asking.
func (r Reviewer) Review(ctx context.Context, mode Mode, facts Facts) (Verdict, error) {
	if mode == Strict && strictNumberedPlaceholder(facts.Username) {
		return Verdict{Decision: DecisionRefuse,
			Reason: "Strict mode refuses a generic numbered username."}, nil
	}
	cohort := cohortFor(facts)
	undecided := func(reason string, err error) (Verdict, error) {
		decision := DecisionRestrict
		if mode == Loose {
			decision = DecisionAllow
		} else if mode == Strict {
			decision = DecisionRefuse
		}
		return cohort.protect(Verdict{Decision: decision, Reason: reason}), err
	}

	if r.Registry == nil || r.Resolve == nil {
		// Nothing configured is not a failure of the review; it is the review
		// being off, and off allows in every mode.
		return Verdict{Decision: DecisionAllow, Reason: "未配置审查模型"}, nil
	}
	upstream, spec, err := r.Resolve(ctx)
	if err != nil {
		return undecided("审查模型不可用", fmt.Errorf("screening: resolve: %w", err))
	}

	ctx, cancel := context.WithTimeout(ctx, Timeout)
	defer cancel()

	var customPrompt string
	if r.Prompt != nil {
		customPrompt = r.Prompt()
	} else if r.CustomPrompt != nil {
		customPrompt = r.CustomPrompt()
	}

	// The answer comes back on Result. The sink is there because the adapters
	// deliver through it as well and a nil one panics, but what it receives
	// depends on the protocol and on whether streaming was used — Result.Text
	// is the same string either way.
	var answer strings.Builder
	result, err := r.Registry.Chat(ctx, upstream, adapter.ChatRequest{
		Model:    spec,
		System:   instructionFor(mode, customPrompt),
		Messages: []adapter.Message{question(facts)},
		// Enough for the object and a sentence. A model that wants to write an
		// essay is cut off, and a cut-off answer follows the mode's fallback.
		MaxTokens: 200,
		Stream:    false,
	}, func(event adapter.Event) error {
		if event.Type == adapter.EventDelta {
			answer.WriteString(event.Text)
		}
		return nil
	})
	if err != nil {
		return undecided("审查请求失败", fmt.Errorf("screening: ask: %w", err))
	}

	said := result.Text
	if strings.TrimSpace(said) == "" {
		said = answer.String()
	}

	verdict, ok := parse(said)
	if !ok {
		// Reported. A model that keeps answering with something
		// this cannot read is a review that is quietly not running, and an
		// operator who is never told has a switch that does nothing. The
		// answer goes in the error so they can see what it actually said.
		return undecided("模型返回内容无法解析",
			fmt.Errorf("screening: unusable answer: %q", clip(said, 200)))
	}
	return cohort.protectModel(verdict), nil
}

// question is the message the facts travel in.
//
// Kind, not just Text: a part with the zero Kind is not a text part and the
// adapters drop it. Without it the model received the instruction and no
// details, and answered — correctly — that it had nothing to judge, which
// this read as an unusable answer and allowed. A whole feature switched on
// and doing nothing, for one missing field.
func question(facts Facts) adapter.Message {
	return adapter.Message{
		Role:  adapter.RoleUser,
		Parts: []adapter.Part{{Kind: adapter.PartText, Text: describe(facts)}},
	}
}

// How much of any one submitted fact reaches the prompt. Longer than any
// field this server accepts, so it only ever truncates something that was not
// checked on the way in.
const maxFactChars = 200

var lineBreaks = strings.NewReplacer("\n", " ", "\r", " ", " ", " ", " ", " ")

// describe lays the facts out one per line, labelled, with nothing else in
// the message — no prose the submitted values could be mistaken for.
func describe(facts Facts) string {
	var out strings.Builder
	write := func(label, value string) {
		if strings.TrimSpace(value) == "" {
			value = "(none)"
		}
		// Newlines inside a submitted value would let it forge a line of its
		// own in this list. U+2028 and U+2029 are line breaks to a model even
		// though they are not to a search for "\n".
		value = lineBreaks.Replace(value)
		// Bounded here rather than assumed to be bounded already: the user
		// agent is a header nothing on this path checks, and a caller that can
		// put sixty kilobytes into the prompt can push the instructions out of
		// the model's attention, or its answer past the token limit — where an
		// unparseable answer is admitted rather than refused.
		value = text.TrimAndTruncate(value, maxFactChars)
		fmt.Fprintf(&out, "%s: %s\n", label, value)
	}

	write("Username", facts.Username)
	write("Nickname", facts.Nickname)
	write("Email", facts.Email)
	write("QQ", facts.QQ)
	write("User agent", facts.UserAgent)
	fmt.Fprintf(&out, "Accounts already created from this address recently: %d\n", facts.FromThisAddress)
	write("Recent registration cohort (past three hours)", cohortFor(facts).description())
	return out.String()
}

// parse reads the verdict out of whatever came back.
//
// Models wrap JSON in prose and in code fences however firmly they are asked
// not to, so the object is taken from the first brace to the last rather than
// from the whole string. Anything that still will not parse follows the
// selected mode's fallback — see the note at the top of the file.
func parse(raw string) (Verdict, bool) {
	start := strings.Index(raw, "{")
	end := strings.LastIndex(raw, "}")
	if start < 0 || end <= start {
		return Verdict{}, false
	}

	var body struct {
		Decision *Decision `json:"decision"`
		Reason   string    `json:"reason"`
	}
	if err := json.Unmarshal([]byte(raw[start:end+1]), &body); err != nil {
		return Verdict{}, false
	}
	if body.Decision == nil {
		// An object with no verdict in it is an answer to a different
		// question, and guessing which way it meant is the one thing this
		// must not do.
		return Verdict{}, false
	}
	switch *body.Decision {
	case DecisionAllow, DecisionRestrict, DecisionRefuse:
		return Verdict{Decision: *body.Decision, Reason: strings.TrimSpace(body.Reason)}, true
	default:
		return Verdict{}, false
	}
}

// clip keeps a log line to one line's worth of somebody else's output.
//
// The cut goes through text.Truncate so it lands on a character boundary: a
// model answering in Chinese is the ordinary case here, and the byte offset
// this used to take could split a character and put invalid bytes into the
// error the operator is meant to read.
func clip(value string, limit int) string {
	value = strings.TrimSpace(value)
	cut := text.Truncate(value, limit)
	if cut == value {
		return value
	}
	return cut + "…"
}
